#!/usr/bin/env bun

import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"
import type { ContentEntry } from "@adaptive-ds/website-content-pipeline"
import type { ContentArticleBody } from "./app/content/ContentArticleBody.ts"
import type { ContentMeta } from "./app/content/ContentMeta.ts"
import { contentCollectionConfig } from "./app/content/contentCollectionConfig.ts"
import type { ContentCollection } from "./app/content/contentCollectionSchema.ts"
import { contentEntryList } from "./app/content/contentEntryList.ts"
import { contentMarkdownRender } from "./app/content/contentMarkdownRender.ts"
import { contentMetaParse } from "./app/content/contentMetaParse.ts"
import { contentSourceParse } from "./app/content/contentSourceParse.ts"

// Compiles content/ratgeber and content/guides (listed by content:process) into:
// - src/app/content/contentMetaList.ts        client-safe metadata (category, keywords, reading time, ...)
// - src/app/content/contentArticleBodyList.ts server-only HTML, headings and FAQ per article
const contentDir = join(process.cwd(), "src", "app", "content")
const collections = Object.keys(contentCollectionConfig) as ContentCollection[]
const metaList: Record<string, Record<string, ContentMeta>> = {}
const bodyList: Record<string, Record<string, ContentArticleBody>> = {}
const failures: string[] = []

for (const collection of collections) {
  metaList[collection] = {}
  bodyList[collection] = {}
  for (const entry of contentEntryList(collection)) {
    const compiled = await entryCompile(collection, entry)
    if (compiled === undefined) continue
    metaList[collection][entry.id] = compiled.meta
    bodyList[collection][entry.id] = compiled.body
  }
}

if (failures.length > 0) {
  console.error(`[contentCompile] failed:\n${failures.map((failure) => `- ${failure}`).join("\n")}`)
  process.exit(1)
}

const header =
  "// Auto-generated by src/contentCompile.ts from content/{ratgeber,guides}/*.md. Manual changes will be lost.\n"
await outputWrite(
  "contentMetaList.ts",
  header +
    "// Client-safe article metadata, keyed by collection and entry id.\n" +
    'import type { ContentCollection } from "./contentCollectionSchema.ts"\n' +
    'import type { ContentMeta } from "./ContentMeta.ts"\n\n' +
    "export const contentMetaList: Readonly<Record<ContentCollection, Readonly<Record<string, ContentMeta>>>> = " +
    JSON.stringify(metaList, null, 2) +
    "\n",
)
await outputWrite(
  "contentArticleBodyList.ts",
  header +
    "// Server-only: import this module only via dynamic import() inside a server function handler.\n" +
    'import type { ContentArticleBody } from "./ContentArticleBody.ts"\n' +
    'import type { ContentCollection } from "./contentCollectionSchema.ts"\n\n' +
    "export const contentArticleBodyList: Readonly<Record<ContentCollection, Readonly<Record<string, ContentArticleBody>>>> =\n  " +
    JSON.stringify(bodyList, null, 2).replaceAll("\n", "\n  ") +
    "\n",
)
// Keep the generated files in the project's Biome format so reruns do not churn git diffs.
const format = Bun.spawnSync(
  [
    "bunx",
    "--no-install",
    "biome",
    "format",
    "--write",
    "src/app/content/contentMetaList.ts",
    "src/app/content/contentArticleBodyList.ts",
  ],
  { cwd: process.cwd(), stdout: "ignore", stderr: "inherit" },
)
if (format.exitCode !== 0) process.exitCode = 1
console.log(
  `[contentCompile] ${collections.map((collection) => `${collection}=${Object.keys(metaList[collection] ?? {}).length}`).join(", ")}`,
)

async function entryCompile(
  collection: ContentCollection,
  entry: ContentEntry,
): Promise<{ meta: ContentMeta; body: ContentArticleBody } | undefined> {
  const source = await readFile(join(process.cwd(), entry.contentPath), "utf8")
  const parsed = contentSourceParse(source)
  if (!parsed.success) {
    failures.push(`${entry.contentPath}: ${parsed.errorMessage}`)
    return undefined
  }
  const extended = contentMetaParse(parsed.data.data)
  if (!extended.success) {
    failures.push(`${entry.contentPath}: ${extended.errorMessage}`)
    return undefined
  }
  const rendered = contentMarkdownRender(parsed.data.body, contentCollectionConfig[collection].lang)
  return {
    meta: {
      collection,
      lang: contentCollectionConfig[collection].lang,
      category: extended.data.category,
      keywords: extended.data.keywords,
      translationKey: extended.data.translationKey,
      seoTitle: extended.data.seoTitle,
      readingMinutes: rendered.readingMinutes,
      wordCount: rendered.wordCount,
    },
    body: { html: rendered.html, headings: rendered.headings, faq: rendered.faq, publicPath: entry.path },
  }
}

async function outputWrite(fileName: string, output: string): Promise<void> {
  const path = join(contentDir, fileName)
  const current = await readFile(path, "utf8").catch(() => undefined)
  if (current !== output) await writeFile(path, output, "utf8")
}
