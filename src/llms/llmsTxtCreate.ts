import type { ContentListItem } from "../app/content/ContentListItem.ts"

/** Escapes characters that would break a markdown link label. */
function llmsLinkTextEscape(value: string): string {
  return value.replace(/[[\]\\]/gu, (character) => `\\${character}`)
}

function llmsArticleLineCreate(siteUrl: string, item: ContentListItem): string {
  const url = new URL(item.entry.path, siteUrl).toString()
  return `- [${llmsLinkTextEscape(item.entry.title)}](${url}): ${item.entry.description.replace(/\s+/gu, " ").trim()}`
}

/**
 * `/llms.txt` (llmstxt.org format): site summary, product facts, key pages and one section per
 * content collection listing every published article as `- [Title](url): description`.
 */
export function llmsTxtCreate(input: {
  readonly siteUrl: string
  readonly ratgeber: readonly ContentListItem[]
  readonly guides: readonly ContentListItem[]
}): string {
  const url = (path: string) => new URL(path, input.siteUrl).toString()
  const section = (title: string, items: readonly ContentListItem[]) => [
    `## ${title}`,
    "",
    ...(items.length === 0
      ? ["- (no articles published yet)"]
      : items.map((item) => llmsArticleLineCreate(input.siteUrl, item))),
    "",
  ]
  return [
    "# Eventoren",
    "",
    "> Eventoren (eventoren.de) is a German online ticketing platform for event organisers: clubs and associations (Vereine), schools, companies and private organisers sell tickets online, check guests in by QR code and get paid out by bank transfer. Interface in German, prices in EUR. Operator: Semesterkur UG (haftungsbeschränkt), Köln, Germany.",
    "",
    "Key facts (as of November 2026):",
    "",
    "- Fee: 3.9 % of the gross ticket price + EUR 0.49 per paid ticket, including VAT and payment processing. No base fee, no minimum revenue, no minimum term. Free tickets cost nothing. The organisation decides at onboarding whether buyers or the organiser pay the fee.",
    "- Buyers check out as guests without an account and receive tickets by email as a PDF with a QR code. Payment methods: card (Visa, Mastercard, Maestro, American Express), Apple Pay and Google Pay where supported, Klarna, SEPA direct debit, Bancontact.",
    "- Ticket types with their own capacity and max-per-order limit; one-time unlock codes (Freischaltcodes) for exclusive presales, generated by the Eventoren team on request.",
    "- Entry: shareable scanner links let helpers scan QR codes in the smartphone browser (no app install, internet required); cashless box office via QR poster; guest list with quotas and plus-ones.",
    "- Team roles, CSV/XLSX/PDF/ICS exports, payout to the organiser's IBAN at the latest on the 7th bank working day after the event.",
    "- Organisers (Verein, Unternehmen, Schule, Privatperson) are checked and approved before sales start.",
    "",
    "## Key pages",
    "",
    `- [Events](${url("/")}): Public event listings; buy tickets for published events.`,
    `- [Kontakt](${url("/kontakt")}): Contact for organisers who want to sell tickets with Eventoren.`,
    `- [Ratgeber](${url("/ratgeber")}): German guides for event organisers (ticketing, entry, law and tax, planning).`,
    `- [Guides](${url("/en/guides")}): English guides for event organisers in Europe.`,
    "",
    ...section("Ratgeber (Deutsch)", input.ratgeber),
    ...section("Guides (English)", input.guides),
  ].join("\n")
}
